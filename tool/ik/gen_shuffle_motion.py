#!/usr/bin/env python
"""Riffle shuffle + square-up: a joint trajectory for the two YAM arms with
Sharpa hands, generated by IK from the layout of the C-IPC "precision card shuffle" scene.

The reference has no hands: every card is held by two Dirichlet rows -- its
lower-outer short edge and its upper-inner short edge -- which bow the two
tented packets, release the cards one by one from the bottom, and two plates
then square the pile. Here the hands take over those roles:

  four fingertips -> the packet's lower-outer END FACE, pinned at table level
                     (all four on the edge line; distal phalanges near
                     vertical, 7-35 deg off -- the long middle finger has to
                     curl to land on the others' line); during the riffle
                     they double as the outer stops
  thumb tip       -> the upper-inner end face: presses down to bow the packet,
                     then -- the THUMB ALONE, arm and fingers still -- slides
                     across the packet's thickness (up and outward), letting
                     the cards spring off from the bottom; the right hand
                     leads the left by one solver step, as in the reference
  fingertip rake  -> the plates, and the square-up: the same four fingertips,
                     side by side (6.1 cm across, inside the 7 cm card depth),
                     sweep the pile's ends toward the centre at the plates'
                     constant speed (4 cm/s x scale), from where the plates
                     start to the card
                     length + --square-slack (the plates stop 0.7 cm short of
                     one squared stack), hold, back off and leave.
                     (Flat parallel "plate" hands do not work on this rig:
                     the two arms are identical, not mirrored, so the left
                     forearm rides inboard of its wrist and the forearms
                     cross over the pile. The hands therefore lean in a few
                     degrees at the end of the push.)

Geometry is the reference's scaled by --scale (default 1.25: the Sharpa hand
is ~1.25x a human hand, so the cards become 11.1 x 7.0 cm), floor = the table
(z = 0), packets --zlift above it (0.6 cm; reference 0.07 cm scaled). It is
meant to be adapted on the cards' side; the file records what it aimed for.

    uv run python tool/ik/gen_shuffle_motion.py [options] --out output/ik/<name>   # -> shuffle_motion.npz, report.json
    uv run python tool/bake_hand_shuffle.py --motion output/ik/<name>/shuffle_motion.npz --out asset/<asset>

The robot model (URDFs and meshes) is asset/robot/yam_sharpa, loaded through tool/robot; the options that
produced the shipped motions are in the README.

Output npz (lengths cm, rig frame: Z up, table z = 0, robot at y ~ 0):
  joint_q [F, 56] rad   left arm 6 + hand 22, right arm 6 + hand 22 (bench order)
  fps, phase_names / phase_start / phase_end (inclusive frame ranges)
  body_q [F, 86, 7]     world link transforms (xyz cm + quaternion xyzw), body_names
  joint_names
  target_left / target_right [F, 7]   thumb-tip target xyz, middle-fingertip
                        target xyz, mode (0 grasp, 1 rake), in WORLD
                        coordinates of each hand; NaN where a phase does not
                        steer that contact (joint-space moves, parked thumb)
  table_exact_cm [F]    lowest robot mesh vertex above the table (exact)
  arm_gap_cm [F]        left-right gap by covering spheres (conservative)
  arm_gap_exact_cm [F]  mesh gap by vertices (stride 4, forearm outward; reads
                        up to 0.1 cm high), every 3rd frame (NaN elsewhere)
  thumb_finger_gap_cm [F]  thumb to the same hand's fingers (covering spheres)
  scene                 json: scale, card size, packet pose, contact points, floor
"""
